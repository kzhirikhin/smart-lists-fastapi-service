from pathlib import Path

from pydantic_settings import BaseSettings, SettingsConfigDict

# Корень репозитория вычисляется от самого файла настроек: `app/core/config.py`.
_REPO_ROOT = Path(__file__).resolve().parents[2]


class Settings(BaseSettings):
    # Путь к `.env` абсолютный, а не относительный. Прежний `".env"` означал не
    # «файл рядом с сервисом», а «файл рядом с текущим каталогом процесса», и
    # это не теория: запуск скрипта из каталога соседнего репозитория подсунул
    # сервису `.env` веб-приложения.
    #
    # `extra="ignore"` — вторая половина той же истории и более опасная. По
    # умолчанию лишние ключи dotenv-файла запрещены, а pydantic перечисляет их
    # в тексте `ValidationError` **вместе со значениями**. Посторонний `.env`
    # приводил поэтому не просто к падению на старте, а к печати чужих секретов
    # в лог. Ошибка конфигурации не должна быть способом раскрыть секрет.
    #
    # Цена названа честно: опечатка в имени переменной внутри `.env` теперь не
    # заметна — значение молча не применится. Касается это только локальной
    # разработки, где `.env` и существует; в Cloud Run его нет, переменные
    # приходят из окружения, а обязательные поля по-прежнему роняют старт, если
    # их не задать.
    model_config = SettingsConfigDict(env_file=_REPO_ROOT / ".env", extra="ignore")

    debug: bool = False

    # Проверка вызывающего по Google ID-токену. Оба значения несекретные:
    # email service account и адрес самого сервиса. `SERVICE_AUDIENCE`
    # принимает список через запятую — у сервиса Cloud Run бывает несколько
    # действующих адресов, и токен выпускается под тот, что настроен у
    # вызывающего.
    #
    # Обязательные: shared secret удалён, и других способов аутентификации не
    # осталось. Отсутствие любого из них означает сервис, который не может
    # никого пустить, — падать на старте честнее, чем отвечать 403 на всё.
    expected_caller_sa: str
    service_audience: str

settings = Settings() # type: ignore[call-arg]
